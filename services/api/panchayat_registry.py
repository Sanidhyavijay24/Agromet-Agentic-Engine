# Alias map for case-insensitive and plain-name lookups (e.g. "shahpura" -> "SHAHPURA_009")
_ALIAS_MAP: dict[str, str] = {}
for pid, meta in PANCHAYAT_REGISTRY.items():
    _ALIAS_MAP[pid.lower()] = pid
    _ALIAS_MAP[meta.name.lower()] = pid
    _ALIAS_MAP[meta.name_hi] = pid
    base_key = pid.rsplit("_", 1)[0].lower()
    _ALIAS_MAP[base_key] = pid


def get_panchayat(identifier: str) -> PanchayatMetadata | None:
    """
    Look up a panchayat by canonical ID (e.g. "KADERA_001", "SHAHPURA_009") or name alias ("Shahpura", "shahpura").
    """
    if not identifier:
        return None
    cleaned = identifier.strip().lower()
    canonical_id = _ALIAS_MAP.get(cleaned)
    if canonical_id and canonical_id in PANCHAYAT_REGISTRY:
        return PANCHAYAT_REGISTRY[canonical_id]
    if identifier.strip().upper() in PANCHAYAT_REGISTRY:
        return PANCHAYAT_REGISTRY[identifier.strip().upper()]
    return None


def list_panchayats() -> list[PanchayatMetadata]:
    """Return canonical pilot panchayats in order."""
    return [PANCHAYAT_REGISTRY[pid] for pid in PILOT_PANCHAYAT_IDS if pid in PANCHAYAT_REGISTRY]


def list_all_panchayats() -> list[PanchayatMetadata]:
    """Return all registered pilot and multi-region panchayats."""
    return list(PANCHAYAT_REGISTRY.values())
