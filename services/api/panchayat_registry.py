    """
    Canonical metadata definition for a Gram Panchayat pilot site or regional agromet station.
    """
    panchayat_id: str
    name: str
    name_hi: str
    district: str
    block: str
    latitude: float
    longitude: float
    elevation_m: float
    crop: str
    crop_hi: str
    crop_stage: str
    default_advisory_en: str
    default_advisory_hi: str
    # Optional. When known, the crop stage is estimated from growing-degree days since
    # this date instead of the static crop_stage above. Left unset for every registry
    # entry on purpose: no real sowing dates are on record, and inventing them would
    # pass fiction off as a GDD estimate. Supply it per request (?sowing_date=) instead.
    sowing_date: date | None = None


